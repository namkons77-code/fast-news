-- Supabase SQL Editor에서 실행하여 빅카인즈 오늘의 키워드 테이블 생성
CREATE TABLE IF NOT EXISTS public.trend_keywords (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name TEXT NOT NULL,
    category_code TEXT NOT NULL,
    entity_name TEXT NOT NULL,
    entity_type TEXT NOT NULL,
    count INTEGER NOT NULL DEFAULT 0,
    step TEXT DEFAULT 'step1',
    news_count INTEGER DEFAULT 0,
    crawled_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 인덱스 생성 (조회 성능 최적화)
CREATE INDEX IF NOT EXISTS idx_trend_cat_crawl ON public.trend_keywords(category_name, crawled_at DESC);
CREATE INDEX IF NOT EXISTS idx_trend_type ON public.trend_keywords(entity_type);
CREATE INDEX IF NOT EXISTS idx_trend_crawl ON public.trend_keywords(crawled_at DESC);

-- RLS 비활성화 (모든 사용자 읽기/쓰기 허용)
ALTER TABLE public.trend_keywords DISABLE ROW LEVEL SECURITY;
GRANT ALL ON TABLE public.trend_keywords TO anon, authenticated, service_role;
